"""
run_experiment.py
------------------
End-to-end experimental pipeline that mirrors Section 4 ("Results and
discussion") of the paper:

    Okorie, Gnatchiglo & Wesseh (2024), "Electricity and cryptocurrency
    mining: An empirical contribution", Heliyon 10, e33483.

Where the paper's quantitative evaluation lives
--------------------------------------------------
Section 4 and its Tables 1-6 are the article's experimental part:
  Table 1  descriptive statistics + Jarque-Bera + Ljung-Box on returns/hash rates
  Table 2  ADF stationarity tests on prices, hash rates and electricity indexes
  Table 3  parametric + nonparametric Granger causality: crypto price <-> hash rate
  Table 4  parametric + nonparametric Granger causality: crypto return -> electricity
           demand, by electricity-cost quantile (Q25/Q50/Q75/Q100)
  Table 5  the same test on a global electricity index
  Table 6  Wald tests for volatility spillover from the asymmetric BEKK(1,1) model

This script reproduces the same *procedure* end to end (Tables 1, 2, 3/5-style
Granger tests, and 6) on:
  (a) synthetic data generated by dgp.py with a known ground-truth causal and
      spillover structure, so you can check that the tests recover it, or
  (b) your own two-column CSV (e.g. real Bitcoin returns and an electricity
      series), passed with --csv.

Usage
-----
    python run_experiment.py                      # synthetic data, default DGP
    python run_experiment.py --n-obs 1000 --seed 7
    python run_experiment.py --csv my_data.csv --col-crypto btc_ret --col-elec elec_growth
"""

from __future__ import annotations

import argparse
import sys
import numpy as np
import pandas as pd
from scipy import stats
from statsmodels.tsa.stattools import adfuller
from statsmodels.stats.diagnostic import acorr_ljungbox

import dgp
import granger_tests as gt
import bekk_model as bekk


def descriptive_table(data: pd.DataFrame) -> pd.DataFrame:
    """Table 1 style: mean, variance, skewness, kurtosis, Jarque-Bera, Ljung-Box, ADF@I(0)."""
    rows = []
    for col in data.columns:
        s = data[col].dropna().to_numpy()
        jb_stat, jb_p = stats.jarque_bera(s)
        lb = acorr_ljungbox(s, lags=[10], return_df=True)
        lb2 = acorr_ljungbox(s ** 2, lags=[10], return_df=True)
        adf_stat, adf_p, *_ = adfuller(s, autolag="AIC", result_object=False)
        rows.append({
            "Series": col,
            "Obs.": len(s),
            "Mean": round(s.mean(), 4),
            "Variance": round(s.var(), 6),
            "Skewness": round(stats.skew(s), 4),
            "Kurtosis": round(stats.kurtosis(s, fisher=False), 4),
            "Jarque-Bera": f"{jb_stat:.2f}{_stars(jb_p)}",
            "LB-Q(10)": f"{lb['lb_stat'].iloc[0]:.2f}{_stars(lb['lb_pvalue'].iloc[0])}",
            "LB-Q2(10)": f"{lb2['lb_stat'].iloc[0]:.2f}{_stars(lb2['lb_pvalue'].iloc[0])}",
            "ADF@I(0)": f"{adf_stat:.3f}{_stars(adf_p)}",
        })
    return pd.DataFrame(rows)


def _stars(p: float) -> str:
    if p < 0.01:
        return "***"
    if p < 0.05:
        return "**"
    if p < 0.10:
        return "*"
    return ""


def stationarity_table(data: pd.DataFrame) -> pd.DataFrame:
    """Table 2 style: ADF on levels and first differences."""
    rows = []
    for col in data.columns:
        level = data[col].dropna().to_numpy()
        diff = np.diff(level)
        lvl_stat, lvl_p, *_ = adfuller(level, autolag="AIC", result_object=False)
        d_stat, d_p, *_ = adfuller(diff, autolag="AIC", result_object=False)
        rows.append({
            "Series": col,
            "I(0) stat": f"{lvl_stat:.3f}{_stars(lvl_p)}",
            "I(1) stat": f"{d_stat:.3f}{_stars(d_p)}",
            "Stationary at": "I(0)" if lvl_p < 0.05 else "I(1)",
        })
    return pd.DataFrame(rows)


def run_granger_block(data: pd.DataFrame, nonparam_subsample: int, seed: int) -> pd.DataFrame:
    """Table 3/4/5 style: parametric + nonparametric Granger causality, both
    directions, on the (already stationary) series in `data`."""
    cols = list(data.columns)
    assert len(cols) == 2
    a, b = cols

    sub = data.iloc[-nonparam_subsample:] if len(data) > nonparam_subsample else data

    results = [
        gt.parametric_granger_causality(data, cause=a, effect=b),
        gt.nonparametric_granger_causality(sub, cause=a, effect=b, seed=seed),
        gt.parametric_granger_causality(data, cause=b, effect=a),
        gt.nonparametric_granger_causality(sub, cause=b, effect=a, seed=seed),
    ]
    return gt.results_table(results)


def run_bekk_block(data: pd.DataFrame, seed: int, maxlags: int = 5) -> tuple[bekk.BEKKResult, pd.DataFrame]:
    """Fits a VAR(p) mean equation, then the asymmetric BEKK(1,1) on its
    residuals, and returns the Table 6 style Wald tests."""
    from statsmodels.tsa.api import VAR

    p = max(gt.select_var_order(data, maxlags=maxlags), 1)
    var_model = VAR(data).fit(p)
    resid = var_model.resid.to_numpy()

    result = bekk.fit_gjr_bekk(resid, seed=seed)
    table = bekk.spillover_wald_tests(result)
    return result, table


def make_stationary(data: pd.DataFrame) -> pd.DataFrame:
    """Differences any column that fails an ADF stationarity test at 5%,
    mirroring the paper's use of "variables at the point of stationarity"."""
    out = {}
    for col in data.columns:
        s = data[col].dropna()
        _, p, *_ = adfuller(s, autolag="AIC", result_object=False)
        out[col] = s.diff().dropna() if p >= 0.05 else s
    min_len = min(len(v) for v in out.values())
    return pd.DataFrame({k: v.iloc[-min_len:].reset_index(drop=True) for k, v in out.items()})


def monte_carlo(n_reps: int, n_obs: int, nonparam_subsample: int, base_seed: int, maxlags: int = 5) -> pd.DataFrame:
    """Repeats simulate -> test n_reps times with a fixed, known DGP (dgp.DGPParams
    defaults) and reports empirical rejection rates (at the 5% level) for every
    hypothesis tested. Since the ground truth is known by construction, a
    rejection rate for a *false* null is an estimate of the test's power, and a
    rejection rate for a *true* null is an estimate of its (empirical) size /
    Type-I error rate. This is the actual "experimental part" of a simulation
    study: it checks whether the estimators/tests in granger_tests.py and
    bekk_model.py behave the way the theory says they should.
    """
    params = dgp.DGPParams()
    truth = {
        "crypto->electricity (VAR)": params.var_causal_structure()["crypto_causes_electricity (phi_21)"],
        "electricity->crypto (VAR)": params.var_causal_structure()["electricity_causes_crypto (phi_12)"],
        "electricity->crypto (BEKK vol.)": params.bekk_spillover_structure()["electricity_vol_spills_to_crypto (x21 or y21)"],
        "crypto->electricity (BEKK vol.)": params.bekk_spillover_structure()["crypto_vol_spills_to_electricity (x12 or y12)"],
        "asymmetric BEKK spillover": params.bekk_spillover_structure()["asymmetric_spillover (z12 or z21)"],
    }

    counters = {k: 0 for k in truth}
    completed = 0
    for r in range(n_reps):
        seed = base_seed + r
        try:
            A, _ = dgp.simulate(params, n_obs=n_obs, seed=seed)
            data = dgp.to_dataframe(A)
            stat_data = make_stationary(data)
            sub = stat_data.iloc[-nonparam_subsample:] if len(stat_data) > nonparam_subsample else stat_data

            g1 = gt.parametric_granger_causality(stat_data, cause="crypto_return", effect="electricity_demand")
            g2 = gt.parametric_granger_causality(stat_data, cause="electricity_demand", effect="crypto_return")
            _, wald_table = run_bekk_block(stat_data, seed=seed, maxlags=maxlags)

            counters["crypto->electricity (VAR)"] += int(g1.p_value < 0.05)
            counters["electricity->crypto (VAR)"] += int(g2.p_value < 0.05)
            counters["electricity->crypto (BEKK vol.)"] += int(wald_table.iloc[0]["P-Value"] < 0.05)
            counters["crypto->electricity (BEKK vol.)"] += int(wald_table.iloc[1]["P-Value"] < 0.05)
            counters["asymmetric BEKK spillover"] += int(wald_table.iloc[2]["P-Value"] < 0.05)
            completed += 1
        except Exception as e:  # keep the Monte Carlo going even if one draw fails to fit
            print(f"[replication {r} failed: {e}]", file=sys.stderr)

    rows = []
    for k, v in truth.items():
        rate = counters[k] / completed if completed else float("nan")
        rows.append({
            "Hypothesis (alternative = link present)": k,
            "True in DGP?": v,
            "Rejection rate @5%": round(rate, 3),
            "Interpretation": "Power" if v else "Empirical size (Type-I error)",
        })
    return pd.DataFrame(rows), completed


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--csv", type=str, default=None, help="path to a 2-column CSV of real data instead of simulating")
    parser.add_argument("--col-crypto", type=str, default="crypto_return")
    parser.add_argument("--col-elec", type=str, default="electricity_demand")
    parser.add_argument("--n-obs", type=int, default=1200, help="simulated sample size")
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--nonparam-subsample", type=int, default=250, help="sub-sample size for the O(n^2) nonparametric test")
    parser.add_argument("--out", type=str, default="results.md", help="output markdown report path")
    parser.add_argument("--monte-carlo", type=int, default=0, help="if > 0, run this many simulate+test replications and report empirical rejection rates (power/size) instead of a single detailed report")
    args = parser.parse_args()

    if args.monte_carlo > 0:
        table, completed = monte_carlo(args.monte_carlo, args.n_obs, args.nonparam_subsample, args.seed)
        header = f"# Monte Carlo check ({completed}/{args.monte_carlo} replications completed, n_obs={args.n_obs} each)\n"
        out_text = header + "\n" + table.to_markdown(index=False)
        with open(args.out, "w") as f:
            f.write(out_text)
        print(out_text)
        print(f"\n[saved to {args.out}]", file=sys.stderr)
        return

    if args.csv:
        raw = pd.read_csv(args.csv)
        data = raw[[args.col_crypto, args.col_elec]].rename(
            columns={args.col_crypto: "crypto_return", args.col_elec: "electricity_demand"}
        ).dropna()
        ground_truth = None
    else:
        params = dgp.DGPParams()
        A, _ = dgp.simulate(params, n_obs=args.n_obs, seed=args.seed)
        data = dgp.to_dataframe(A)
        ground_truth = {
            "VAR (mean) causal structure": params.var_causal_structure(),
            "BEKK volatility spillover structure": params.bekk_spillover_structure(),
        }

    report = []
    report.append("# Experimental report: VAR / Granger causality / GJR-BEKK\n")
    report.append(f"Data source: {'CSV -> ' + args.csv if args.csv else 'simulated (dgp.py, seed=' + str(args.seed) + ', n_obs=' + str(args.n_obs) + ')'}\n")

    if ground_truth:
        report.append("## Ground truth built into the simulated data\n")
        for block, d in ground_truth.items():
            report.append(f"**{block}**")
            for k, v in d.items():
                report.append(f"- {k}: `{v}`")
            report.append("")

    report.append("## Table 1 - Descriptive statistics (paper Table 1 style)\n")
    desc = descriptive_table(data)
    report.append(desc.to_markdown(index=False))
    report.append("")

    report.append("## Table 2 - Stationarity (ADF) tests (paper Table 2 style)\n")
    stat_table = stationarity_table(data)
    report.append(stat_table.to_markdown(index=False))
    report.append("")

    stationary_data = make_stationary(data)

    report.append("## Tables 3/5 - Granger causality, crypto return <-> electricity demand (paper Table 3-5 style)\n")
    granger_table = run_granger_block(stationary_data, args.nonparam_subsample, args.seed)
    report.append(granger_table.to_markdown(index=False))
    report.append("")

    report.append("## Table 6 - GJR-BEKK volatility spillover Wald tests (paper Table 6 style)\n")
    bekk_result, wald_table = run_bekk_block(stationary_data, seed=args.seed)
    report.append(f"VAR-BEKK log-likelihood: {bekk_result.loglik:.2f} | optimizer converged: {bekk_result.converged}\n")
    report.append(wald_table.to_markdown(index=False))
    report.append("")
    report.append("### Estimated BEKK parameters\n")
    report.append(bekk_result.summary_frame().round(4).to_markdown(index=False))
    report.append("")

    out_text = "\n".join(report)
    with open(args.out, "w") as f:
        f.write(out_text)

    print(out_text)
    print(f"\n[saved to {args.out}]", file=sys.stderr)


if __name__ == "__main__":
    main()
